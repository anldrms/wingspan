import type { Geometry } from "./silhouette";

export type Category =
  | "widebody"
  | "narrowbody"
  | "regional"
  | "business"
  | "general-aviation"
  | "cargo"
  | "military"
  | "supersonic"
  | "historic";

export interface Aircraft {
  slug: string;
  name: string;
  manufacturer: string;
  /** ICAO type designator. */
  icao: string;
  category: Category;
  firstFlight: number;
  /** Overall height (m). */
  height: number;
  /** Maximum take-off weight (tonnes). */
  mtow: number;
  /** Typical capacity, free text. */
  capacity: string;
  /** Approximate cruise speed (km/h). */
  cruise: number;
  geometry: Geometry;
}

